# Regenerates the embedded SPIR-V sources of the modules that own GLSL shaders. Each module keeps its GLSL
# next to the code that embeds it:
#   app/shaders/*.vert|frag   -> app/src/Shaders/EmbeddedShaders.cpp   (composite + debug draw, CPU and GPU lines)
#   imgui/shaders/*.vert|frag -> imgui/src/Shaders/ImGuiShaders.cpp    (Dear ImGui renderer)
#   scene/shaders/*.vert|frag -> scene/src/Shaders/SceneShaders.cpp    (mesh renderer)
# Usage: powershell -File tools/generate-embedded-shaders.ps1 [-Glslc <path to glslc.exe>]
param(
    [string]$Glslc = "glslc"
)

$ErrorActionPreference = "Stop"
$ProjectRoot = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)

$AppShaders = @(
    @{ Source = "Composite.vert"; Function = "CompositeVertexShader"; Namespace = "luvk::app::shaders" },
    @{ Source = "Composite.frag"; Function = "CompositeFragmentShader"; Namespace = "luvk::app::shaders" },
    @{ Source = "DebugDraw.vert"; Function = "DebugDrawVertexShader"; Namespace = "luvk::app::shaders" },
    @{ Source = "DebugDraw.frag"; Function = "DebugDrawFragmentShader"; Namespace = "luvk::app::shaders" },
    @{ Source = "DebugDrawGpu.vert"; Function = "DebugDrawGpuVertexShader"; Namespace = "luvk::app::shaders" }
)

$SceneShaders = @(
    @{ Source = "Mesh.vert"; Function = "MeshVertexShader"; Namespace = "luvk::scene::shaders" },
    @{ Source = "Mesh.frag"; Function = "MeshFragmentShader"; Namespace = "luvk::scene::shaders" }
)

$ImGuiShaders = @(
    @{ Source = "ImGui.vert"; Function = "ImGuiVertexShader"; Namespace = "luvk::imgui::shaders" },
    @{ Source = "ImGui.frag"; Function = "ImGuiFragmentShader"; Namespace = "luvk::imgui::shaders" }
)

function Write-ShaderFile {
    param(
        [string]$Output,
        [string]$Header,
        [string]$SourceDir,
        [array]$Shaders
    )

    $Body = [System.Text.StringBuilder]::new()
    [void]$Body.AppendLine("// Author: Lucas Vilas-Boas")
    [void]$Body.AppendLine("// Year: 2026")
    [void]$Body.AppendLine("// Repo : https://github.com/lucoiso/luvk")
    [void]$Body.AppendLine("//")
    [void]$Body.AppendLine("// Generated by tools/generate-embedded-shaders.ps1 - do not edit by hand.")
    [void]$Body.AppendLine()
    [void]$Body.AppendLine("#include `"$Header`"")
    [void]$Body.AppendLine()

    foreach ($Shader in $Shaders) {
        $Source = Join-Path $SourceDir $Shader.Source
        $Spirv = Join-Path ([System.IO.Path]::GetTempPath()) ($Shader.Source + ".spv")
        & $Glslc --target-env=vulkan1.3 -O -o $Spirv $Source
        if ($LASTEXITCODE -ne 0) {
            throw "glslc failed for $($Shader.Source)"
        }

        $Bytes = [System.IO.File]::ReadAllBytes($Spirv)
        $Words = [System.Collections.Generic.List[string]]::new()
        for ($Index = 0; $Index -lt $Bytes.Length; $Index += 4) {
            $Word = [System.BitConverter]::ToUInt32($Bytes, $Index)
            $Words.Add("0x{0:X8}U" -f $Word)
        }

        [void]$Body.AppendLine("namespace")
        [void]$Body.AppendLine("{")
        [void]$Body.AppendLine("    constexpr std::uint32_t $($Shader.Function)Code[] = {")
        for ($Index = 0; $Index -lt $Words.Count; $Index += 8) {
            $End = [Math]::Min($Index + 8, $Words.Count) - 1
            $Line = "        " + ($Words[$Index..$End] -join ", ")
            [void]$Body.AppendLine($Line + ",")
        }
        [void]$Body.AppendLine("    };")
        [void]$Body.AppendLine("}")
        [void]$Body.AppendLine()
        Remove-Item $Spirv -Force
    }

    [void]$Body.AppendLine("namespace $($Shaders[0].Namespace)")
    [void]$Body.AppendLine("{")
    foreach ($Shader in $Shaders) {
        [void]$Body.AppendLine("    std::span<const std::uint32_t> $($Shader.Function)()")
        [void]$Body.AppendLine("    {")
        [void]$Body.AppendLine("        return $($Shader.Function)Code;")
        [void]$Body.AppendLine("    }")
        [void]$Body.AppendLine()
    }
    [void]$Body.AppendLine("}")

    [System.IO.File]::WriteAllText($Output, $Body.ToString())
    Write-Host "Generated $Output"
}

$AppHeader = @'
// Author: Lucas Vilas-Boas
// Year: 2026
// Repo : https://github.com/lucoiso/luvk

#pragma once

#include <cstdint>
#include <span>

namespace luvk::app::shaders
{
    /** SPIR-V of the fullscreen composite vertex shader. */
    [[nodiscard]] std::span<const std::uint32_t> CompositeVertexShader();

    /** SPIR-V of the fullscreen composite fragment shader. */
    [[nodiscard]] std::span<const std::uint32_t> CompositeFragmentShader();

    /** SPIR-V of the debug draw line vertex shader. */
    [[nodiscard]] std::span<const std::uint32_t> DebugDrawVertexShader();

    /** SPIR-V of the debug draw line fragment shader. */
    [[nodiscard]] std::span<const std::uint32_t> DebugDrawFragmentShader();

    /** SPIR-V of the vertex shader pulling GPU-written debug lines through a buffer device address. */
    [[nodiscard]] std::span<const std::uint32_t> DebugDrawGpuVertexShader();
}
'@

$ImGuiHeader = @'
// Author: Lucas Vilas-Boas
// Year: 2026
// Repo : https://github.com/lucoiso/luvk

#pragma once

#include <cstdint>
#include <span>

namespace luvk::imgui::shaders
{
    /** SPIR-V of the Dear ImGui vertex shader. */
    [[nodiscard]] std::span<const std::uint32_t> ImGuiVertexShader();

    /** SPIR-V of the Dear ImGui fragment shader. */
    [[nodiscard]] std::span<const std::uint32_t> ImGuiFragmentShader();
}
'@

$SceneHeader = @'
// Author: Lucas Vilas-Boas
// Year: 2026
// Repo : https://github.com/lucoiso/luvk

#pragma once

#include <cstdint>
#include <span>

namespace luvk::scene::shaders
{
    /** SPIR-V of the mesh renderer vertex shader (vertex pulling, instanced). */
    [[nodiscard]] std::span<const std::uint32_t> MeshVertexShader();

    /** SPIR-V of the mesh renderer fragment shader (unlit / lit materials). */
    [[nodiscard]] std::span<const std::uint32_t> MeshFragmentShader();
}
'@

[System.IO.File]::WriteAllText((Join-Path $ProjectRoot "app\src\Shaders\EmbeddedShaders.hpp"), $AppHeader)
[System.IO.File]::WriteAllText((Join-Path $ProjectRoot "imgui\src\Shaders\ImGuiShaders.hpp"), $ImGuiHeader)

Write-ShaderFile -Output (Join-Path $ProjectRoot "app\src\Shaders\EmbeddedShaders.cpp") -Header "EmbeddedShaders.hpp" -SourceDir (Join-Path $ProjectRoot "app\shaders") -Shaders $AppShaders
New-Item -ItemType Directory -Force -Path (Join-Path $ProjectRoot "scene\src\Shaders") | Out-Null
[System.IO.File]::WriteAllText((Join-Path $ProjectRoot "scene\src\Shaders\SceneShaders.hpp"), $SceneHeader)
Write-ShaderFile -Output (Join-Path $ProjectRoot "scene\src\Shaders\SceneShaders.cpp") -Header "SceneShaders.hpp" -SourceDir (Join-Path $ProjectRoot "scene\shaders") -Shaders $SceneShaders

Write-ShaderFile -Output (Join-Path $ProjectRoot "imgui\src\Shaders\ImGuiShaders.cpp") -Header "ImGuiShaders.hpp" -SourceDir (Join-Path $ProjectRoot "imgui\shaders") -Shaders $ImGuiShaders
